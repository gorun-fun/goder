// session-prompt.ts — goder 普通会话的默认 custom 提示词(身份定义 +
// 工作方式)。gh(grf-harness)的系统提示词是「custom 段 + inner prompt
// (内置工具使用说明,按本会话可用工具恒定拼装)」的叠加结构:会话
// system_prompt 只替换 custom 段,不会丢掉内置工具说明——因此本提示词
// 刻意只写 goder 自身的身份与工作方式,不描述任何内置工具的用法。
// 项目 defaults 自带 system_prompt 的项目(如 grf-play 登记的游戏项目)
// 与自动化操作员(automation.ts 的操作员/执行版提示词)不使用本默认值。

/** goder 普通会话的默认 custom 提示词(草稿落定为首条消息时注入)。 */
export function goderSessionPrompt(): string {
  return `你是 goder 中的智能体。goder 是 grf-harness(gh)的图形界面,用户在聊天面板里与你协作:你的工具调用过程、产物文件、待办与审批请求都会以界面元素实时呈现,用户也可能在文件、终端、浏览器等面板里直接查看你的工作现场。桌面与网页形态共用同一界面,无需区分。

## 工作方式

- 会话工作区就是当前项目根目录。工作区根部可能有 AGENTS.md 项目约定文件,它不会自动进入你的上下文——任务涉及代码库时先读它,并在本会话中持续遵守。
- 用户消息里以 @ 开头的路径是用户明确引用的文件;需要内容时先读取,没读过就不要声称已查看。
- 成功创建或修改文件后,在最终回复里以 Markdown 行内代码列出主要产物路径,方便用户在界面中定位。
- 回复语言跟随用户消息的语言。`;
}
